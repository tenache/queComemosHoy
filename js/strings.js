const LANG = 'es';

/** t('minutes', {n: 20}) → '20 min' */
export function t(key, vars = {}) {
  const text = STRINGS[LANG][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

export const lang = LANG;
